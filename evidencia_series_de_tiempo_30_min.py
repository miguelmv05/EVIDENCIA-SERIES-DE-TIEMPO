# Random Walk model
def random_walk_forecast(series, steps=30):
    last_value = series.iloc[-1]
    np.random.seed(42)  # For reproducibility
    random_steps = np.random.normal(loc=0, scale=series.diff().std(), size=steps)
    forecast = last_value + np.cumsum(random_steps)
    return forecast

