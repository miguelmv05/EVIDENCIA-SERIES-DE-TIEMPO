# ARCH and GARCH modeling with visualization
def fit_arch_garch(series, name):
    # Calculate returns (percentage change)
    returns = series.pct_change().dropna() * 100

    # ARCH(1) model
    arch_model_fit = arch_model(returns, vol='ARCH', p=1).fit(disp='off')
    print(f"\nARCH(1) Model for {name}:")
    print(arch_model_fit.summary())

    # GARCH(1,1) model
    garch_model_fit = arch_model(returns, vol='GARCH', p=1, q=1).fit(disp='off')
    print(f"\nGARCH(1,1) Model for {name}:")
    print(garch_model_fit.summary())

    # Forecast volatility for next 30 periods
    garch_forecast = garch_model_fit.forecast(horizon=30)
    forecast_vol = np.sqrt(garch_forecast.variance.values[-1, :])

    print(f"\nGARCH Volatility Forecast for {name} (next 5 periods):")
    print(forecast_vol[:5])

    # Plot historical conditional volatility
    plt.figure(figsize=(12, 6))
    plt.plot(garch_model_fit.conditional_volatility, label='GARCH(1,1) Conditional Volatility')
    plt.title(f'{name} Historical Conditional Volatility (GARCH)')
    plt.xlabel('Time')
    plt.ylabel('Volatility (%)')
    plt.legend()
    plt.savefig(f'{name}_garch_historical_volatility.png')
    plt.show()
    plt.close()

    # Plot forecasted volatility
    forecast_index = range(1, 31)
    plt.figure(figsize=(12, 6))
    plt.plot(forecast_index, forecast_vol, label='GARCH(1,1) Forecasted Volatility', color='red')
    plt.title(f'{name} Forecasted Volatility (GARCH, 30 Periods)')
    plt.xlabel('Forecast Horizon')
    plt.ylabel('Volatility (%)')
    plt.legend()
    plt.savefig(f'{name}_garch_forecast_volatility.png')
    plt.show()
    plt.close()

    return arch_model_fit, garch_model_fit, forecast_vol

